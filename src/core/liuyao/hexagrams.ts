export const HEXAGRAMS: readonly HexagramEntry[] = RAW.map(
  ([name, theme, reading], i) => ({
    n: i + 1,
    name,
    theme,
    reading,
    glyph: String.fromCodePoint(0x4dc0 + i),
  }),
)

export function hexagramByNumber(n: number): HexagramEntry | null {
  if (!Number.isInteger(n) || n < 1 || n > HEXAGRAMS.length) {
    return null
  }
  return HEXAGRAMS[n - 1]
}
